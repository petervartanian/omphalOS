"""Command-line access to the same workflow served by the local workbench."""

from __future__ import annotations

import argparse
import json
import logging
import sys
import uuid
from pathlib import Path
from typing import Any

from . import __version__
from .models import REVIEW_ADAPTER, Analysis, Case
from .runner import Workspace
from .util import (
    OmphalOSError,
    atomic_write,
    canonical_json,
    read_json,
    safe_child,
    safe_id,
)


def parser() -> argparse.ArgumentParser:
    app = argparse.ArgumentParser(
        prog="omphalos",
        description="Local transaction investigations with traceable evidence and explicit review.",
    )
    app.add_argument("--version", action="version", version=f"omphalOS {__version__}")
    app.add_argument(
        "--workspace", type=Path, default=Path.home() / "omphalos-workspace"
    )
    app.add_argument(
        "--debug", action="store_true", help="Include diagnostic tracebacks on errors"
    )
    commands = app.add_subparsers(dest="command", required=True)
    commands.add_parser("init", help="Create a local workspace")
    commands.add_parser("status", help="List datasets, snapshots, cases, and runs")
    commands.add_parser("catalog", help="Describe the implemented investigations")
    schema = commands.add_parser("schema", help="Print a versioned JSON schema")
    schema.add_argument("kind", choices=("case", "review", "analysis", "data"))
    dataset = commands.add_parser(
        "import", help="Import validated CSV files or dataset.json"
    )
    dataset.add_argument("directory", type=Path)
    dataset.add_argument("--id", required=True)
    dataset.add_argument("--label", default="")
    sources = commands.add_parser(
        "sources", help="Inspect or import official screening snapshots"
    )
    actions = sources.add_subparsers(dest="source_action", required=True)
    actions.add_parser("catalog")
    actions.add_parser("list")
    for action in ("fetch", "import"):
        sub = actions.add_parser(action)
        sub.add_argument("source_id", choices=("csl", "ofac_sdn", "ofac_non_sdn"))
        if action == "import":
            sub.add_argument("file", type=Path)
        sub.add_argument("--id", default=None, help="Snapshot ID; generated by default")
    case = commands.add_parser(
        "case", help="Save an investigation question, scope, and parameters"
    )
    case.add_argument("file", type=Path)
    for command, help_text in (
        ("run", "Execute the selected investigations for a saved case"),
        ("show", "Show a run, evidence summary, review, and verification"),
        ("replay", "Recompute a run from retained inputs with the recorded engine"),
        ("export", "Export a reviewed run into a portable evidence bundle"),
        (
            "review-template",
            "Write an incomplete review template for an analyst to fill in",
        ),
    ):
        sub = commands.add_parser(command, help=help_text)
        sub.add_argument("id", help="Case ID" if command == "run" else "Run ID")
        if command == "export":
            sub.add_argument("--review-id", default=None)
        if command == "review-template":
            sub.add_argument("--output", type=Path, required=True)
    review = commands.add_parser(
        "review", help="Validate and record a completed analyst review"
    )
    review.add_argument("file", type=Path)
    verify = commands.add_parser(
        "verify", help="Verify a run ID, run directory, or evidence ZIP"
    )
    verify.add_argument("target")
    signature = commands.add_parser(
        "verify-signature",
        help="Verify a detached Ed25519 signature against an external trusted key",
    )
    signature.add_argument("artifact", type=Path)
    signature.add_argument("signature", type=Path)
    signature.add_argument("trusted_public_key", type=Path)
    serve = commands.add_parser(
        "serve", help="Open the offline local analyst workbench"
    )
    serve.add_argument("--host", default="127.0.0.1")
    serve.add_argument("--port", type=int, default=8765)
    serve.add_argument("--open", action="store_true", dest="open_browser")
    team = commands.add_parser(
        "team", help="Manage an optional authenticated team server"
    )
    team_actions = team.add_subparsers(dest="team_action", required=True)
    team_init = team_actions.add_parser(
        "init", help="Create the first team administrator"
    )
    team_init.add_argument("--username", required=True)
    team_init.add_argument("--name", required=True)
    team_serve = team_actions.add_parser(
        "serve", help="Serve the shared team workspace"
    )
    team_serve.add_argument("--host", default="127.0.0.1")
    team_serve.add_argument("--port", type=int, default=8770)
    team_serve.add_argument("--origin", default=None)
    team_serve.add_argument("--certfile", type=Path)
    team_serve.add_argument("--keyfile", type=Path)
    team_serve.add_argument("--behind-proxy", action="store_true")
    return app


def dispatch(args: argparse.Namespace) -> dict | list | None:
    from .data import data_schema, import_dataset
    from .evidence import verify_bundle, verify_ed25519_signature, verify_run
    from .investigations import catalog
    from .sources import fetch_source, import_source, source_catalog

    if args.command == "catalog":
        return catalog()
    if args.command == "schema":
        if args.kind == "review":
            return REVIEW_ADAPTER.json_schema()
        return (
            data_schema()
            if args.kind == "data"
            else {"case": Case, "analysis": Analysis}[args.kind].model_json_schema()
        )
    if args.command == "verify-signature":
        return verify_ed25519_signature(
            args.artifact, args.signature, args.trusted_public_key
        )
    if args.command == "verify":
        target = Path(args.target)
        if target.exists() or any(char in args.target for char in ("/", "\\", ".")):
            return (
                verify_bundle(target)
                if target.suffix.lower() == ".zip"
                else verify_run(target)
            )
    if args.command == "sources" and args.source_action == "catalog":
        return source_catalog()
    if args.command == "team":
        if args.team_action == "init":
            import getpass

            from .team_store import TeamStore

            store = TeamStore(args.workspace)
            if store.initialized():
                raise OmphalOSError(
                    "This team is already initialized. Use its administrator account."
                )
            password = getpass.getpass("Administrator passphrase (14–256 characters): ")
            repeated = getpass.getpass("Repeat passphrase: ")
            if password != repeated:
                raise OmphalOSError("The passphrases did not match.")
            return store.create_user(args.username, args.name, password, is_admin=True)
        from .team import serve_team

        serve_team(
            args.workspace,
            host=args.host,
            port=args.port,
            origin=args.origin,
            certfile=args.certfile,
            keyfile=args.keyfile,
            behind_proxy=args.behind_proxy,
        )
        return None
    workspace = Workspace(args.workspace)
    if args.command == "init":
        return {"workspace": str(workspace.root), "version": __version__}
    if args.command == "status":
        return {
            "workspace": str(workspace.root),
            "datasets": workspace.list_datasets(),
            "sources": workspace.list_sources(),
            "cases": workspace.list_cases(),
            "runs": workspace.list_runs(),
        }
    if args.command == "import":
        return import_dataset(
            args.directory,
            safe_child(workspace.root, f"datasets/{safe_id(args.id)}"),
            label=args.label,
        )
    if args.command == "sources":
        if args.source_action == "catalog":
            return source_catalog()
        if args.source_action == "list":
            return workspace.list_sources()
        snapshot_id = safe_id(
            args.id or args.source_id.replace("_", "-") + "-" + uuid.uuid4().hex[:12]
        )
        destination = safe_child(workspace.root, f"sources/{snapshot_id}")
        if args.source_action == "fetch":
            return fetch_source(args.source_id, destination)
        return import_source(args.source_id, args.file, destination)
    if args.command == "case":
        return workspace.save_case(read_json(args.file))
    if args.command == "run":
        return workspace.run_case(args.id)
    if args.command == "show":
        return workspace.get_run(args.id)
    if args.command == "replay":
        return workspace.replay_run(args.id)
    if args.command == "export":
        return workspace.export_run(args.id, review_id=args.review_id)
    if args.command == "review":
        review = read_json(args.file)
        if not isinstance(review, dict) or "run_id" not in review:
            raise OmphalOSError("Review must be an object containing run_id.")
        return workspace.save_review(review["run_id"], review)
    if args.command == "review-template":
        run = workspace.get_run(args.id)
        # Deliberately invalid until a human writes the assessment and acknowledges limits.
        template: dict[str, Any] = {
            "schema_version": "2.0",
            "run_id": args.id,
            "reviewer": "",
            "summary": "",
            "findings": [
                {
                    "finding_id": f["finding_id"],
                    "disposition": "follow_up",
                    "rationale": "",
                    "unknowns": [],
                    "alternatives": [],
                    "falsifiers": [],
                }
                for f in run["analysis"]["findings"]
            ],
            "acknowledge_limitations": False,
        }
        if args.output.exists():
            raise OmphalOSError(
                "Review template output already exists; choose a new path."
            )
        atomic_write(
            args.output,
            json.dumps(template, ensure_ascii=False, indent=2).encode("utf-8") + b"\n",
        )
        return {
            "path": str(args.output.resolve()),
            "status": "incomplete",
            "findings_to_review": len(template["findings"]),
        }
    if args.command == "verify":
        return workspace.verify_run(args.target)
    if args.command == "serve":
        from .web import serve

        serve(
            workspace.root,
            host=args.host,
            port=args.port,
            open_browser=args.open_browser,
        )
        return None
    raise OmphalOSError("Unsupported command.")


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    if args.debug:
        logging.basicConfig(level=logging.DEBUG)
    try:
        result = dispatch(args)
        if result is not None:
            sys.stdout.buffer.write(canonical_json(result))
        return 1 if isinstance(result, dict) and result.get("ok") is False else 0
    except KeyboardInterrupt:
        return 130
    except (ValueError, OSError, KeyError, TypeError) as exc:
        if args.debug:
            raise
        print(
            json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False),
            file=sys.stderr,
        )
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
